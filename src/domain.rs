//! Validated vector strokes and conservative rendering bounds.

use serde::{Deserialize, Serialize};
use thiserror::Error;
use uuid::Uuid;

/// Absolute world-coordinate limit shared with the frontend.
pub const WORLD_LIMIT: f64 = 1_000_000_000.0;
const BOUNDS_EPSILON: f64 = 1.0;

/// Brush shapes in JSON v1.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Brush {
    /// Rounded caps and joins.
    Round,
    /// Square caps with bevel joins; a single point is an axis-aligned square.
    Square,
    /// Flat calligraphic nib fixed at -45 degrees in world space, swept between points.
    Chisel,
    /// Deterministic particle cloud seeded by the lowercase stroke UUID (spray v1).
    Spray,
}

impl Brush {
    /// Wire and database representation.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Round => "round",
            Self::Square => "square",
            Self::Chisel => "chisel",
            Self::Spray => "spray",
        }
    }

    /// Parses a stored database value; unknown values are rejected, never defaulted.
    pub fn from_stored(value: &str) -> Option<Self> {
        match value {
            "round" => Some(Self::Round),
            "square" => Some(Self::Square),
            "chisel" => Some(Self::Chisel),
            "spray" => Some(Self::Spray),
            _ => None,
        }
    }
}

/// Untrusted client payload. Validation is required before storage.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct StrokeInput {
    /// Idempotency key generated by the client.
    pub id: Uuid,
    /// World-coordinate pairs in input order.
    pub points: Vec<[f64; 2]>,
    /// Brush shape.
    pub brush: Brush,
    /// Diameter/side length in world units (CSS pixels at scale 1).
    pub width: f64,
    /// Hex RGB, normalized to uppercase on validation.
    pub color: String,
    /// Opacity of the whole stroke.
    pub opacity: f64,
}

/// Configurable validation limits. Construction rejects nonsensical limits.
#[derive(Debug, Clone, Copy)]
pub struct StrokeLimits {
    max_points: usize,
    max_span: f64,
}

impl StrokeLimits {
    /// Constructs limits. Span is the maximum extent of the input points on either axis.
    ///
    /// # Errors
    /// Returns an error for zero points or a nonpositive, nonfinite, oversized span.
    pub fn new(max_points: usize, max_span: f64) -> Result<Self, ValidationError> {
        if max_points == 0
            || !max_span.is_finite()
            || !(0.0..=2.0 * WORLD_LIMIT).contains(&max_span)
            || max_span == 0.0
        {
            return Err(ValidationError::InvalidLimits);
        }
        Ok(Self {
            max_points,
            max_span,
        })
    }

    /// Maximum number of sampled points.
    pub fn max_points(self) -> usize {
        self.max_points
    }

    /// Maximum point-cloud span on each axis, before adding brush padding.
    pub fn max_span(self) -> f64 {
        self.max_span
    }
}

impl Default for StrokeLimits {
    fn default() -> Self {
        Self {
            max_points: 2000,
            max_span: 100_000.0,
        }
    }
}

/// A server-computed rectangle; deliberately not deserializable from a client.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Bounds {
    /// Left edge, including brush padding.
    pub min_x: f64,
    /// Top edge, including brush padding.
    pub min_y: f64,
    /// Right edge, including brush padding.
    pub max_x: f64,
    /// Bottom edge, including brush padding.
    pub max_y: f64,
}

/// A normalized stroke whose payload can only be created through validation.
#[derive(Debug, Clone, PartialEq)]
pub struct ValidatedStroke {
    input: StrokeInput,
    bounds: Bounds,
}

impl ValidatedStroke {
    /// Normalized public input, without ownership or server metadata.
    pub fn input(&self) -> &StrokeInput {
        &self.input
    }

    /// Server-computed conservative bounding box.
    pub fn bounds(&self) -> Bounds {
        self.bounds
    }
}

/// Validation failure without echoing any user-controlled payload.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum ValidationError {
    /// The server configuration itself is invalid.
    #[error("invalid stroke limits")]
    InvalidLimits,
    /// Empty or too densely sampled stroke.
    #[error("point count outside allowed limits")]
    PointCount,
    /// A point contains a nonfinite or out-of-world value.
    #[error("coordinate outside allowed range")]
    Coordinate,
    /// The gesture spans too much of the world.
    #[error("stroke extent exceeds allowed limits")]
    Extent,
    /// Width is not finite or outside [1, 64].
    #[error("width must be between 1 and 64")]
    Width,
    /// Color is not exactly #RRGGBB.
    #[error("color must be a six-digit hex RGB value")]
    Color,
    /// Opacity is not finite or outside (0, 1].
    #[error("opacity must be greater than zero and at most one")]
    Opacity,
}

impl StrokeInput {
    /// Validates and normalizes the payload, without smoothing or changing the trajectory.
    ///
    /// # Errors
    /// Returns a safe, typed failure for invalid geometry or brush parameters.
    pub fn validate(mut self, limits: StrokeLimits) -> Result<ValidatedStroke, ValidationError> {
        if self.points.is_empty() || self.points.len() > limits.max_points {
            return Err(ValidationError::PointCount);
        }
        if !self.width.is_finite() || !(1.0..=64.0).contains(&self.width) {
            return Err(ValidationError::Width);
        }
        if !self.opacity.is_finite() || self.opacity <= 0.0 || self.opacity > 1.0 {
            return Err(ValidationError::Opacity);
        }
        let color = self.color.as_bytes();
        if color.len() != 7 || color[0] != b'#' || !color[1..].iter().all(u8::is_ascii_hexdigit) {
            return Err(ValidationError::Color);
        }
        self.color.make_ascii_uppercase();

        let mut bounds = Bounds {
            min_x: f64::INFINITY,
            min_y: f64::INFINITY,
            max_x: f64::NEG_INFINITY,
            max_y: f64::NEG_INFINITY,
        };
        for &[x, y] in &self.points {
            if !valid_coordinate(x) || !valid_coordinate(y) {
                return Err(ValidationError::Coordinate);
            }
            bounds.min_x = bounds.min_x.min(x);
            bounds.min_y = bounds.min_y.min(y);
            bounds.max_x = bounds.max_x.max(x);
            bounds.max_y = bounds.max_y.max(y);
        }
        if bounds.max_x - bounds.min_x > limits.max_span
            || bounds.max_y - bounds.min_y > limits.max_span
        {
            return Err(ValidationError::Extent);
        }

        // Diagonal square caps protrude farther on an axis than width / 2.
        // A -45 degree chisel nib of length `width` fits the same conservative
        // square extent; spray particles stay inside a disc of diameter `width`.
        let padding = match self.brush {
            Brush::Round | Brush::Spray => self.width / 2.0,
            Brush::Square | Brush::Chisel => self.width / std::f64::consts::SQRT_2,
        } + BOUNDS_EPSILON;
        bounds.min_x -= padding;
        bounds.min_y -= padding;
        bounds.max_x += padding;
        bounds.max_y += padding;
        Ok(ValidatedStroke {
            input: self,
            bounds,
        })
    }
}

fn valid_coordinate(value: f64) -> bool {
    value.is_finite() && (-WORLD_LIMIT..=WORLD_LIMIT).contains(&value)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stroke() -> StrokeInput {
        StrokeInput {
            id: Uuid::new_v4(),
            points: vec![[0.0, 0.0], [10.0, 5.0]],
            brush: Brush::Round,
            width: 6.0,
            color: "#aB12ef".into(),
            opacity: 0.8,
        }
    }

    #[test]
    fn normalizes_color_without_changing_points() {
        let input = stroke();
        let points = input.points.clone();
        let validated = input.validate(StrokeLimits::default()).unwrap();
        assert_eq!(validated.input().color, "#AB12EF");
        assert_eq!(validated.input().points, points);
        assert_eq!(
            validated.bounds(),
            Bounds {
                min_x: -4.0,
                min_y: -4.0,
                max_x: 14.0,
                max_y: 9.0
            }
        );
    }

    #[test]
    fn single_point_has_nonempty_bounds_for_every_brush() {
        for brush in [Brush::Round, Brush::Square, Brush::Chisel, Brush::Spray] {
            let mut input = stroke();
            input.points = vec![[4.0, -5.0]];
            input.brush = brush;
            let bounds = input.validate(StrokeLimits::default()).unwrap().bounds();
            assert!(bounds.min_x < 4.0 && bounds.max_x > 4.0);
            assert!(bounds.min_y < -5.0 && bounds.max_y > -5.0);
        }
    }

    #[test]
    fn diagonal_square_caps_fit_inside_bounds() {
        let mut input = stroke();
        input.points = vec![[0.0, 0.0], [10.0, 10.0]];
        input.brush = Brush::Square;
        input.width = 64.0;
        let bounds = input.validate(StrokeLimits::default()).unwrap().bounds();
        let cap_extent = 64.0 / std::f64::consts::SQRT_2;
        assert!(bounds.min_x < -cap_extent);
        assert!(bounds.min_y < -cap_extent);
        assert!(bounds.max_x > 10.0 + cap_extent);
        assert!(bounds.max_y > 10.0 + cap_extent);
    }

    #[test]
    fn chisel_nib_and_spray_disc_fit_inside_bounds() {
        let width: f64 = 64.0;
        let mut input = stroke();
        input.points = vec![[0.0, 0.0]];
        input.width = width;
        input.brush = Brush::Chisel;
        let bounds = input
            .clone()
            .validate(StrokeLimits::default())
            .unwrap()
            .bounds();
        // Nib corners: half-length along (1,-1)/sqrt2 plus half-thickness across it.
        let thickness = (width / 6.0).max(1.0);
        let nib_extent = (width + thickness) / (2.0 * std::f64::consts::SQRT_2);
        assert!(bounds.min_x < -nib_extent && bounds.max_x > nib_extent);
        assert!(bounds.min_y < -nib_extent && bounds.max_y > nib_extent);
        input.brush = Brush::Spray;
        let bounds = input.validate(StrokeLimits::default()).unwrap().bounds();
        assert!(bounds.min_x < -width / 2.0 && bounds.max_x > width / 2.0);
        assert!(bounds.min_y < -width / 2.0 && bounds.max_y > width / 2.0);
    }

    #[test]
    fn brush_names_roundtrip_through_storage_and_json() {
        for brush in [Brush::Round, Brush::Square, Brush::Chisel, Brush::Spray] {
            assert_eq!(Brush::from_stored(brush.as_str()), Some(brush));
            assert_eq!(
                serde_json::to_value(brush).unwrap(),
                serde_json::json!(brush.as_str())
            );
        }
        assert_eq!(Brush::from_stored("Round"), None);
    }

    #[test]
    fn accepts_world_edges_and_does_not_clip_brush_padding() {
        for edge in [-WORLD_LIMIT, WORLD_LIMIT] {
            let mut input = stroke();
            input.points = vec![[edge, edge]];
            let bounds = input.validate(StrokeLimits::default()).unwrap().bounds();
            assert!(bounds.min_x < edge && bounds.max_x > edge);
        }
    }

    #[test]
    fn rejects_nonfinite_and_out_of_world_coordinates_on_both_axes() {
        for value in [
            f64::NAN,
            f64::INFINITY,
            f64::NEG_INFINITY,
            WORLD_LIMIT + 1.0,
            -WORLD_LIMIT - 1.0,
        ] {
            for axis in 0..2 {
                let mut input = stroke();
                input.points[0][axis] = value;
                assert_eq!(
                    input.validate(StrokeLimits::default()),
                    Err(ValidationError::Coordinate)
                );
            }
        }
    }

    #[test]
    fn enforces_point_count_and_axis_span() {
        let mut input = stroke();
        input.points.clear();
        assert_eq!(
            input.validate(StrokeLimits::default()),
            Err(ValidationError::PointCount)
        );
        assert_eq!(
            stroke().validate(StrokeLimits::new(1, 100.0).unwrap()),
            Err(ValidationError::PointCount)
        );
        assert!(
            stroke()
                .validate(StrokeLimits::new(2, 10.0).unwrap())
                .is_ok()
        );
        for axis in 0..2 {
            let mut input = stroke();
            input.points[1][axis] = 101.0;
            assert_eq!(
                input.validate(StrokeLimits::new(2, 100.0).unwrap()),
                Err(ValidationError::Extent)
            );
        }
    }

    #[test]
    fn validates_width_and_opacity_boundaries() {
        for width in [1.0, 64.0] {
            let mut input = stroke();
            input.width = width;
            assert!(input.validate(StrokeLimits::default()).is_ok());
        }
        for width in [0.0, 0.9, 64.1, f64::NAN, f64::INFINITY] {
            let mut input = stroke();
            input.width = width;
            assert_eq!(
                input.validate(StrokeLimits::default()),
                Err(ValidationError::Width)
            );
        }
        for opacity in [f64::MIN_POSITIVE, 1.0] {
            let mut input = stroke();
            input.opacity = opacity;
            assert!(input.validate(StrokeLimits::default()).is_ok());
        }
        for opacity in [0.0, -0.1, 1.1, f64::NAN, f64::INFINITY] {
            let mut input = stroke();
            input.opacity = opacity;
            assert_eq!(
                input.validate(StrokeLimits::default()),
                Err(ValidationError::Opacity)
            );
        }
    }

    #[test]
    fn rejects_malformed_and_non_ascii_colors() {
        for color in [
            "",
            "#abc",
            "#abcdef00",
            "abcdef",
            "#GG0000",
            "#00000é",
            "#000000\n",
        ] {
            let mut input = stroke();
            input.color = color.into();
            assert_eq!(
                input.validate(StrokeLimits::default()),
                Err(ValidationError::Color)
            );
        }
    }

    #[test]
    fn rejects_untrusted_metadata_and_malformed_point_shapes() {
        let mut payload = serde_json::to_value(stroke()).unwrap();
        for field in [
            "own",
            "owner_digest",
            "bounds",
            "seq",
            "created_at",
            "deleted_at",
        ] {
            payload[field] = serde_json::json!(true);
            assert!(serde_json::from_value::<StrokeInput>(payload.clone()).is_err());
            payload.as_object_mut().unwrap().remove(field);
        }
        for points in [
            serde_json::json!([[1]]),
            serde_json::json!([[1, 2, 3]]),
            serde_json::json!([[null, 2]]),
        ] {
            payload["points"] = points;
            assert!(serde_json::from_value::<StrokeInput>(payload.clone()).is_err());
        }
        payload["points"] = serde_json::json!([[1, 2]]);
        payload["brush"] = serde_json::json!("triangle");
        assert!(serde_json::from_value::<StrokeInput>(payload).is_err());
    }

    #[test]
    fn invalid_limits_cannot_be_constructed() {
        assert!(StrokeLimits::new(0, 1.0).is_err());
        for span in [0.0, -1.0, f64::NAN, f64::INFINITY, 2.0 * WORLD_LIMIT + 1.0] {
            assert!(StrokeLimits::new(1, span).is_err());
        }
    }
}
